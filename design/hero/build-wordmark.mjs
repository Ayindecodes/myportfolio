// Hero wordmark (task 62): turns "AYINDE" in Fredoka (weight 700, width 100) into SVG paths, so the balloon
// letters render from the server HTML with no font loading and no layout shift. It also outlines the nav logo's
// "ayinde" (task 96), so the first screen never waits on the display font.
//
//   npm run wordmark
//
// Downloads the official Fredoka variable font (SIL Open Font License) into design/.cache/ on first run and
// writes src/components/hero/wordmark.generated.ts. Shapes are in font units (1000 per em), y pointing down,
// baseline at 0.

import { createWriteStream, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { Readable } from "node:stream";
import { finished } from "node:stream/promises";
import { fileURLToPath } from "node:url";
import * as fontkit from "fontkit";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const fontUrl = "https://github.com/google/fonts/raw/main/ofl/fredoka/Fredoka%5Bwdth%2Cwght%5D.ttf";
const fontPath = join(root, "design/.cache/Fredoka-VF.ttf");
const outPath = join(root, "src/components/hero/wordmark.generated.ts");

const text = "AYINDE";
const variation = { wght: 700, wdth: 100 }; // width 100: the six-letter name stays tall enough to read as balloons

if (!existsSync(fontPath)) {
  mkdirSync(dirname(fontPath), { recursive: true });
  const response = await fetch(fontUrl);
  if (!response.ok) throw new Error(`Font download failed: ${response.status}`);
  await finished(Readable.fromWeb(response.body).pipe(createWriteStream(fontPath)));
}

const font = fontkit.openSync(fontPath).getVariation(variation);
const run = font.layout(text); // applies the font's own kerning

const round = (n) => Math.round(n * 10) / 10;
let pen = 0;
const letters = run.glyphs.map((glyph, i) => {
  const position = run.positions[i];
  const x = pen + position.xOffset;
  pen += position.xAdvance;
  const box = glyph.path.bbox; // y up
  return {
    char: text[i],
    x: round(x),
    advance: round(position.xAdvance),
    // y flipped so it points down, like SVG
    box: [round(box.minX), round(-box.maxY), round(box.maxX), round(-box.minY)],
    d: glyph.path.scale(1, -1).toSVG().replace(/-?\d+\.\d+/g, (n) => String(round(Number(n)))),
  };
});

// Nav logo: "ayinde" at 27px in Fredoka 700, width 118, with -0.5px tracking, centred in the logo's 120×40 viewBox
// on a baseline at y = 29 (what the live SVG text used to be).
const logoFont = fontkit.openSync(fontPath).getVariation({ wght: 700, wdth: 118 });
const logoRun = logoFont.layout("ayinde");
const logoScale = 27 / logoFont.unitsPerEm;
const tracking = -0.5;
let logoPen = 0;
const logoGlyphs = logoRun.glyphs.map((glyph, i) => {
  const x = logoPen + logoRun.positions[i].xOffset * logoScale;
  logoPen += logoRun.positions[i].xAdvance * logoScale + tracking;
  return { glyph, x };
});
const logoLeft = 60 - (logoPen - tracking) / 2;
const round2 = (n) => Math.round(n * 100) / 100;
const logoPath = logoGlyphs
  .map(({ glyph, x }) => glyph.path.scale(logoScale, -logoScale).translate(logoLeft + x, 29).toSVG())
  .join("")
  .replace(/-?\d+\.\d+/g, (n) => String(round2(Number(n))));

const source = `// Generated by design/hero/build-wordmark.mjs (npm run wordmark). Do not edit by hand.
// "${text}" in Fredoka (wght ${variation.wght}, wdth ${variation.wdth}), SIL Open Font License.
// Font units (${font.unitsPerEm} per em), y down, baseline at 0. box = [minX, minY, maxX, maxY] relative to x.

export const wordmark = ${JSON.stringify({ capHeight: font.capHeight, width: round(pen), letters }, null, 2)} as const;

// Nav logo "ayinde" (Fredoka wght 700, wdth 118) in the logo's 120×40 viewBox.
export const logoPath = ${JSON.stringify(logoPath)};
`;

writeFileSync(outPath, source);
console.log(`Wrote ${outPath.replace(`${root}/`, "")} (${letters.length} letters, ${(source.length / 1024).toFixed(1)} KB)`);
